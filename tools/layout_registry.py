"""Generate and check the shared layout registry.

Every recovered routine reads byte images at fixed offsets. When each routine
re-derives those offsets, a layout correction has to be found and fixed in
every caller, and nothing catches the ones that were missed. This module makes
`docs/recovery/layouts.json` the single authored source and renders it into a
header of named constants.

The useful half is the drift check. It scans recovered sources for byte-image
offsets and reports any that the registry does not describe, which is the
concrete form of "no translation re-derives a layout". Unregistered offsets are
a work queue, not a failure: plenty of them are legitimately internal to one
routine, and promoting them is a review decision.
"""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RECOVERY = ROOT / 'docs' / 'recovery'
HEADER = ROOT / 'native' / 'include' / 'mco' / 'layouts.hpp'
# Only these image sizes may appear in the drift report; anything else is an
# unrelated constant, a code address or a document offset.
IMAGE_SIZES = (0x2000, 0x820, 0x4a8, 0x984, 0x418, 0x1400)
OFFSET = re.compile(r'\b0x([0-9a-fA-F]{1,4})\b')
SOURCE_DIRECTORIES = ('native/src', 'client')

BANNER = '''#pragma once
// Generated by tools/layout_registry.py from docs/recovery/layouts.json.
// Do not edit by hand: change the registry and regenerate.
//
// These are byte-image offsets established by original-execution comparison.
// They are not recovered C++ class layouts; no vtable, ownership or lifetime
// claim is implied, and a host pointer is never reinterpreted from these
// fields.
#include <array>
#include <cstddef>
'''


def registry(path=RECOVERY / 'layouts.json'):
    document = json.loads(path.read_text(encoding='utf-8'))
    images = document.get('images', {})
    if not images:
        raise ValueError('layout registry has no images')
    for name, image in images.items():
        size = int(image['size'], 16)
        for offset, field in image['fields'].items():
            if not re.fullmatch('0x[0-9a-f]{1,4}', offset) or not field.get('name'):
                raise ValueError(f'{name}: field {offset} needs an offset and a name')
            # A field past the end of its own image is a layout mistake, and it
            # is cheapest to reject it here rather than at render time.
            if int(offset, 16) + field_width(field) > size:
                raise ValueError(f'{name}: {offset} {field["name"]} '
                                 f'exceeds image size {image["size"]}')
    return document


def field_width(field):
    """Legacy fields default to four bytes; packed byte/word fields opt in."""
    width = field.get('width', 4)
    if type(width) is not int or width not in (1, 2, 4, 8):
        raise ValueError('layout field width must be 1, 2, 4 or 8 bytes')
    return width


def render(document):
    """Render the registry into a header of named offset constants."""
    lines = [BANNER.rstrip('\n')]
    for name, image in sorted(document['images'].items()):
        lines.append('')
        lines.append(f'namespace {name} {{')
        lines.append(f'inline constexpr std::size_t size = {image["size"]};')
        size = int(image['size'], 16)
        for offset, field in sorted(image['fields'].items(),
                                    key=lambda item: int(item[0], 16)):
            value = int(offset, 16)
            if value + field_width(field) > size:
                raise ValueError(f'{name}: {offset} {field["name"]} exceeds {size}')
            lines.append(f'inline constexpr std::size_t {field["name"]} = '
                         f'{value:#05x};  // {field["type"]}, {field.get("units", "")}')
        lines.append('}  // namespace ' + name)
    lines.append('')
    return '\n'.join(lines)


def registered(document):
    """Every offset the registry describes, for the drift check."""
    known = set()
    for image in document['images'].values():
        known.update(int(offset, 16) for offset in image['fields'])
    return known


def consumers(document):
    """Return (file, images) pairs for every adopted consumer.

    Attribution is explicit because a bare hex literal carries no image. The
    same number means different things in different images: `0x134` is a
    component field in one loader and a configuration field in wheel setup.
    Guessing from the number alone would merge two unrelated layouts and hide
    exactly the disagreement the audit exists to find.
    """
    adopted = {}
    for relative, images in document.get('consumers', {}).items():
        if not images:
            raise ValueError(f'consumer {relative} names no image')
        adopted[relative] = sorted(images)
    for directory in SOURCE_DIRECTORIES:
        base = ROOT / directory
        if not base.is_dir():
            continue
        for path in sorted(base.rglob('*')):
            if path.suffix not in ('.cpp', '.hpp'):
                continue
            if 'mco/layouts.hpp' in path.read_text(encoding='utf-8',
                                                   errors='replace'):
                relative = f'{path.relative_to(ROOT).as_posix()}'
                adopted.setdefault(relative, sorted(document['images']))
    return sorted(adopted.items())


def non_offsets(document):
    """Byte-image constants that are not field offsets.

    A layout owns its strides and its minimum sizes too. Leaving them
    unregistered would keep the drift report permanently non-empty, which is
    exactly how a useful check becomes ignored noise.
    """
    values = set()
    for image in document['images'].values():
        values.update(int(constant, 16)
                      for constant in image.get('strides', {}))
        if image.get('minimum_size'):
            values.add(int(image['minimum_size'], 16))
    return values


def scan(document):
    """Report byte-image offsets used by layout consumers but unregistered.

    Offsets are split by how many consumers use them. A constant one file uses
    alone cannot drift against anything, and most of a large loader's constants
    are exactly that. An offset several files use is a shared contract, and
    those are the ones the registry must describe.
    """
    known = registered(document) | non_offsets(document)
    sizes = {int(image['size'], 16) for image in document['images'].values()}
    sites = defaultdict(set)
    audited = []
    for relative, images in consumers(document):
        path = ROOT / relative
        if not path.is_file():
            raise ValueError(f'layout consumer {relative} is missing')
        for image in images:
            if image not in document['images']:
                raise ValueError(f'consumer {relative} names unknown image {image}')
        audited.append(relative)
        lines = path.read_text(encoding='utf-8', errors='replace').splitlines()
        for number, line in enumerate(lines, 1):
            for match in OFFSET.finditer(line):
                value = int(match.group(1), 16)
                if value in known or value in sizes or value < 0x40:
                    continue
                sites[value].add(f'{relative}:{number}')
    shared = {value: found for value, found in sites.items()
              if len({site.split(':')[0] for site in found}) > 1}
    local = {value: found for value, found in sites.items()
             if value not in shared}
    return shared, local, audited


def check(document):
    """Report header drift and unregistered offsets."""
    rendered = render(document)
    header_current = HEADER.exists() and HEADER.read_text(encoding='utf-8') == rendered
    shared, local, audited = scan(document)
    return dict(header_current=header_current,
                registered_offsets=len(registered(document)),
                audited_files=len(audited),
                shared_unregistered=len(shared),
                local_unregistered=len(local),
                shared_examples={f'{value:#06x}': sorted(sites)[:3]
                                for value, sites in sorted(shared.items())[:20]})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='report header drift and unregistered offsets')
    args = parser.parse_args()
    document = registry()
    if args.check:
        print(json.dumps(check(document), indent=2))
        return
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_bytes(render(document).encode('utf-8'))
    print(json.dumps(check(document), indent=2))


if __name__ == '__main__':
    main()
