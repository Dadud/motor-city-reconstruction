"""Generate a recovery cell from one manifest entry.

A recovery cell is the unit of work behind every translated routine: a header,
a native source, a self-test, a comparison harness, a CMake fragment, a
comparison driver and the inventory review record. Writing those by hand is
pure boilerplate and is where recovery time actually leaks, so the manifest
becomes the single authored artifact and this module renders the rest.

Recurring design rule for declarations, applied before scaffolding:
an emulated address input becomes an explicit host parameter or span, and a
memory write becomes a returned value or an explicit destination buffer. The
host never dereferences an original address, so a signature that takes
`std::uint32_t` where the original reads through a pointer is wrong before the
first line of the body.

The scaffold is honest about being a scaffold. A scaffolded routine throws and
its self-test fails, so an unimplemented cell can never pass CI by existing.
Nothing here overwrites an authored file: regenerating is refused unless the
target is byte-identical to what this module produced, which keeps the factory
usable as a checker long after the hand-written source has moved on.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CELLS = ROOT / 'docs' / 'recovery' / 'cells'
WORKFLOW = ROOT / '.github' / 'workflows' / 'native.yml'
IDENTIFIER = re.compile('[a-z][a-z0-9_]*')
SIGNATURE = re.compile(r'^\s*(?P<return>[\w:&*<>, ]+?)\s+(?P<name>[A-Za-z_]\w*)'
                       r'\s*\((?P<arguments>[^)]*)\)\s*;\s*$')

HEADER = '''#pragma once
#include <array>
#include <cstddef>
#include <cstdint>
#include <span>
{includes}namespace mco {{
// Original {roots}; {brief}
{decl}
}}
'''

SOURCE = '''#include "mco/{id}.hpp"
#include <stdexcept>

namespace mco {{
{notes}
// Decompiled pseudocode of {first_root}, kept as the implementation draft.
// The oracle against the original, not this text, decides correctness.
{pseudocode}
{stub}
}}  // namespace mco
'''

STUB = '''
{return} {name}({arguments}) {{
    throw std::logic_error(
        "cell {id} scaffolded: implement original {first_root}");
}}
'''

TEST = '''#include "mco/{id}.hpp"
#include <stdexcept>

// A scaffolded cell must fail: an unimplemented recovery cannot pass CI by
// existing. Replace this with the recovered behavior and its bounds.
int main() {{
    throw std::runtime_error(
        "cell {id} is scaffolded: implement original {first_root} first");
}}
'''

COMPARE = '''#include "mco/{id}.hpp"
{comparison_includes}#include "cell_io.hpp"
int main() {{
    return cell_io::run([](std::istream& input) {{
        using namespace cell_io;
{comparison_body}
    }});
}}
'''

FRAGMENT = '''# Generated by tools/function_cell.py from cells/{id}.json.
add_executable(mco_{id}_test native/tests/{id}_test.cpp)
target_link_libraries(mco_{id}_test PRIVATE mco_core)
add_executable(mco_{id}_compare native/tests/{id}_compare.cpp)
target_link_libraries(mco_{id}_compare PRIVATE mco_core)
{registration}'''

# A scaffolded cell builds and registers its comparison harness, but its
# self-test stays out of ctest until the routine is implemented. That keeps the
# suite green for honest reasons rather than by suppressing a deliberate failure.
REGISTERED = '''add_test(NAME {id} COMMAND mco_{id}_test)
set_tests_properties({id} PROPERTIES TIMEOUT 60)
'''

SCAFFOLDED = '''message(STATUS "recovery cell {id} is scaffolded; self-test not registered")
'''

DRIVER = '''"""Replay original-execution cases for {id}; empty corpora fail."""
from tools.cell_corpus import main

if __name__ == '__main__':
    main('{id}')
'''

TEMPLATE = {'.hpp': HEADER, '.cpp': SOURCE, '_test.cpp': TEST,
            '_compare.cpp': COMPARE, '.cmake': FRAGMENT, '.py': DRIVER}


def signature(manifest):
    """Parse the declared function so the scaffold compiles against it."""
    match = SIGNATURE.match(manifest['decl'])
    if not match:
        raise ValueError(f"{manifest['id']}: declaration must be one "
                         'function signature returning a value')
    return match.groupdict()


def load_manifest(path):
    manifest = json.loads(path.read_text(encoding='utf-8'))
    missing = [key for key in ('id', 'roots', 'brief', 'decl', 'bookkeeping')
               if not manifest.get(key)]
    if missing:
        raise ValueError(f'{path.name}: missing {missing}')
    if not IDENTIFIER.fullmatch(manifest['id']):
        raise ValueError(f'{path.name}: id must be a lower snake-case identifier')
    if not manifest['roots'] or not all(re.fullmatch('0x[0-9a-f]+', root['address'])
                                        for root in manifest['roots']):
        raise ValueError(f'{path.name}: every root needs a 0x address')
    if manifest.get('status', 'scaffolded') not in ('scaffolded', 'implemented'):
        raise ValueError(f'{path.name}: status must be scaffolded or implemented')
    signature(manifest)
    return manifest


def artifacts(manifest):
    """Return the generated path and content for every cell artifact."""
    identifier = manifest['id']
    roots = ', '.join(root['address'] for root in manifest['roots'])
    parsed = signature(manifest)
    status = manifest.get('status', 'scaffolded')
    fields = dict(id=identifier, roots=roots, brief=manifest['brief'],
                  includes=''.join(f'#include "{name}"\n' for name in manifest.get('header_includes', [])),
                  comparison_includes=''.join(f'#include "{name}"\n' for name in manifest.get('comparison', {}).get('includes', [])),
                  decl=manifest['decl'],
                  notes='\n'.join(f'// {line}' for line in manifest.get('notes', [])),
                  pseudocode='\n'.join(f'// {line}' for line in
                      manifest.get('pseudocode', '').splitlines()),
                  first_root=manifest['roots'][0]['address'],
                  comparison_body=manifest.get('comparison', {}).get('body',
                      '        throw std::logic_error("cell comparison not implemented");'),
                  **parsed)
    fields['stub'] = STUB.format(**fields)
    fields['registration'] = (REGISTERED if status == 'implemented'
                               else SCAFFOLDED).format(**fields)
    plan = {
        'native/include/mco': '.hpp',
        'native/src': '.cpp',
        'native/tests': '_test.cpp',
        'native/cmds': '.cmake',
    }
    result = {ROOT / directory / f'{identifier}{suffix}':
              TEMPLATE[suffix].format(**fields)
              for directory, suffix in plan.items()}
    result[ROOT / 'native' / 'tests' / f'{identifier}_compare.cpp'] = \
        COMPARE.format(**fields)
    result[ROOT / 'tools' / f'native_{identifier}_compare.py'] = DRIVER.format(
        **fields)
    return result


def review_batch(manifest):
    """Render the inventory review record the cell's sources justify."""
    bookkeeping = dict(manifest['bookkeeping'])
    bookkeeping['sources'] = sorted(str(path.relative_to(ROOT)).replace('\\', '/')
                                    for path in artifacts(manifest))
    if manifest.get('comparison'):
        bookkeeping['sources'] = sorted(set(bookkeeping['sources']) | {
            'tools/w0_cell_corpus.py', 'tools/cell_corpus.py',
            'native/tests/cell_io.hpp'})
    bookkeeping['sources'] = sorted(set(bookkeeping['sources'])
                                    | set(manifest.get('shared_sources', [])))
    dependencies = sorted(set(root['address'] for root in manifest['roots'][1:])
                          | set(manifest.get('depends_on', [])))
    return dict(target_sha256=manifest['roots'][0].get('target_sha256'),
                 functions={root['address']:
                            dict(bookkeeping, dependencies=dependencies)
                            for root in manifest['roots']})


def planned(manifest):
    """Every artifact the manifest owns, including the review record."""
    result = artifacts(manifest)
    result[ROOT / 'docs' / 'recovery' / 'review-batches'
           / f"{manifest['id']}.json"] = json.dumps(
               review_batch(manifest), indent=2) + '\n'
    return result


GENERATED = CELLS / 'generated.json'


def _provenance():
    if GENERATED.exists():
        return json.loads(GENERATED.read_text(encoding='utf-8'))
    return {}


def _record(entries):
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_bytes(
        (json.dumps(entries, indent=1, sort_keys=True) + '\n').encode('utf-8'))


def write_all(manifest, dry_run=False):
    """Write every artifact, refusing to replace human edits.

    Refusing every difference would be unusable: changing a manifest has to
    regenerate the files that embed its notes. So the factory records what it
    wrote last time, and only overwrites a file whose bytes still match that
    record. Anything else carries a human edit and is refused.
    """
    identifier = manifest['id']
    written, refused = [], []
    provenance = _provenance()
    updates = dict(provenance)
    for path, content in planned(manifest).items():
        relative = str(path.relative_to(ROOT)).replace('\\', '/')
        digest = hashlib.sha256(content.encode('utf-8')).hexdigest()
        if path.exists():
            current = hashlib.sha256(
                path.read_bytes()).hexdigest()
            if current == digest:
                updates[relative] = digest
                continue
            if provenance.get(relative) != current:
                refused.append(relative)
                continue
        written.append(relative)
        updates[relative] = digest
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Bytes, not text: Windows newline translation would change the
            # hash and make every later regeneration look like a human edit.
            path.write_bytes(content.encode('utf-8'))
    if not dry_run:
        _record(updates)
    return written, refused


def workflow_steps(identifier):
    """Return the CI steps that run this cell's comparison harness."""
    return [f"      - if: runner.os == 'Linux'\n"
            f"        run: python -m tools.native_{identifier}_compare "
            f"build/native/mco_{identifier}_compare\n",
            f"      - if: runner.os == 'Windows'\n"
            f"        run: python -m tools.native_{identifier}_compare "
            f"build/native/Release/mco_{identifier}_compare.exe\n"]


def check(manifest):
    """Report which generated artifacts are absent, diverged or unimplemented.

    A cell needs no CI wiring of its own: tools/run_cell_comparisons.py reads the
    same manifests, so coverage follows status rather than a workflow edit.
    """
    identifier = manifest['id']
    output = planned(manifest)
    absent = sorted(str(p.relative_to(ROOT)).replace('\\', '/') for p in output
                    if not p.exists())
    stale = sorted(str(p.relative_to(ROOT)).replace('\\', '/') for p, content
                   in output.items()
                   if p.exists() and p.read_text(encoding='utf-8') != content)
    status = manifest.get('status', 'scaffolded')
    return dict(id=identifier, brief=manifest['brief'], status=status,
                absent=absent, diverged=stale,
                ci_compared=status == 'implemented')


def manifests(directory=CELLS):
    """Every cell manifest, excluding the factory's own provenance record."""
    return [path for path in sorted(directory.glob('*.json'))
            if path.name != GENERATED.name]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifest', nargs='*', type=Path,
                        help='cell manifests; defaults to every manifest')
    parser.add_argument('--check', action='store_true',
                        help='report missing or diverged artifacts')
    parser.add_argument('--ci-steps', action='store_true',
                        help='print the CI steps this cell still needs')
    args = parser.parse_args()
    paths = args.manifest or manifests()
    if not paths:
        parser.error(f'no cell manifests in {CELLS}')
    results = []
    for path in paths:
        manifest = load_manifest(path)
        if args.ci_steps:
            results.append(dict(id=manifest['id'],
                                steps=workflow_steps(manifest['id'])))
            continue
        if args.check:
            results.append(check(manifest))
            continue
        written, refused = write_all(manifest)
        results.append(dict(id=manifest['id'], written=written,
                            refused=refused))
    print(json.dumps(results, indent=2))


if __name__ == '__main__':
    main()
